    const dynamicText = (text, language, dictionary) => {
        if (language === 'en') return text;

        const roleMatch = text.match(/^Good day, (.+?)(\s*✦)?$/);
        if (roleMatch) {
            const role = dictionary[roleMatch[1]] || roleLabels[language]?.[roleMatch[1]] || roleMatch[1];
            return `${dictionary['Good day,'] || 'Good day,'} ${role}${roleMatch[2] || ''}`;
        }

        const dedicatedMatch = text.match(/^The dedicated (.+?) module has not been added yet\. Your account is active and only shows the information currently permitted for this role\.$/);
        if (dedicatedMatch) {
            const role = dictionary[dedicatedMatch[1]] || roleLabels[language]?.[dedicatedMatch[1]] || dedicatedMatch[1];
            if (language === 'fr') return `Le module ${role.toLowerCase()} dédié n’est pas encore disponible. Votre compte est actif et n’affiche que les informations autorisées pour ce rôle.`;
            if (language === 'sw') return `Moduli maalum ya ${role} bado haijaongezwa. Akaunti yako inafanya kazi na inaonyesha taarifa zinazoruhusiwa kwa nafasi yako tu.`;
        }

        const invitationRole = text.match(/^Your account is pre-approved for (.+)\. Use this link only if it was sent to you by your hotel administrator\.$/);
        if (invitationRole) {
            const role = dictionary[invitationRole[1]] || invitationRole[1];
            if (language === 'fr') return `Votre compte est préautorisé pour le rôle ${role}. N’utilisez ce lien que s’il vous a été envoyé par l’administrateur de l’hôtel.`;
            if (language === 'sw') return `Akaunti yako imeidhinishwa mapema kwa nafasi ya kazi ya ${role}. Tumia kiungo hiki tu ikiwa umetumiwa na msimamizi wa hoteli.`;
        }

        const bookingMatch = text.match(/^(Pending|Confirmed) booking saved\. Total: (.+) for (\d+) night\(s\)\.$/);
        if (bookingMatch) {
            const status = dictionary[bookingMatch[1]] || bookingMatch[1];
            const nights = Number(bookingMatch[3]);
            if (language === 'fr') return `Réservation ${status.toLowerCase()} enregistrée. Total : ${bookingMatch[2]} pour ${nights} nuit${nights === 1 ? '' : 's'}.`;
            if (language === 'sw') return `Nafasi ${status.toLowerCase()} imehifadhiwa. Jumla: ${bookingMatch[2]} kwa usiku ${nights}.`;
        }

        const checkoutMatch = text.match(/^Guest checked out\. Payment of (.+) recorded\.$/);
        if (checkoutMatch) {
            if (language === 'fr') return `Départ du client enregistré. Paiement de ${checkoutMatch[1]} enregistré.`;
            if (language === 'sw') return `Mgeni ametoka. Malipo ya ${checkoutMatch[1]} yamerekodiwa.`;
        }

        const temporaryPassword = text.match(/^(Staff account created\. Share this temporary password once: |Password reset\. All prior sessions were revoked\. Share this temporary password once: )(.+)$/);
        if (temporaryPassword) {
            const prefix = temporaryPassword[1].startsWith('Staff account')
                ? (language === 'fr' ? 'Compte du personnel créé. Communiquez une seule fois ce mot de passe temporaire : ' : 'Akaunti ya mfanyakazi imetengenezwa. Shiriki nenosiri hili la muda mara moja tu: ')
                : (language === 'fr' ? 'Mot de passe réinitialisé ; toutes les sessions ont été révoquées. Communiquez une seule fois ce mot de passe temporaire : ' : 'Nenosiri limewekwa upya; vipindi vyote vimefungwa. Shiriki nenosiri hili la muda mara moja tu: ');
            return prefix + temporaryPassword[2];
        }

        if (/^Room \d+/.test(text)) {
            return text.replace(/^Room /, language === 'fr' ? 'Chambre ' : 'Chumba ')
                .replace(/\/night\b/g, language === 'fr' ? '/nuit' : '/usiku');
        }
        const roomRate = text.match(/^Floor (\d+) · (.+) per night$/);
        if (roomRate) {
            return language === 'fr'
                ? `Étage ${roomRate[1]} · ${roomRate[2]} par nuit`
                : `Sakafu ${roomRate[1]} · ${roomRate[2]} kwa usiku`;
        }
        const displayOrder = text.match(/^Display order (\d+)$/);
        if (displayOrder) {
            return language === 'fr'
                ? `Ordre d’affichage ${displayOrder[1]}`
                : `Mpangilio wa kuonyesha ${displayOrder[1]}`;
        }
        const bookingNumber = text.match(/^Booking #(\d+)$/);
        if (bookingNumber) {
            return `${dictionary['Booking #'] || 'Booking #'}${bookingNumber[1]}`;
        }
        const referenceNumber = text.match(/^(Room|Staff account|Invitation) #(\d+)$/);
        if (referenceNumber) {
            const labels = language === 'fr'
                ? { Room: 'Chambre', 'Staff account': 'Compte du personnel', Invitation: 'Invitation' }
                : { Room: 'Chumba', 'Staff account': 'Akaunti ya mfanyakazi', Invitation: 'Mwaliko' };
            return `${labels[referenceNumber[1]]} #${referenceNumber[2]}`;
        }
        if (text === '— RWF') return '— RWF';

        return dictionary[text] || text;
    };

    const originalText = new WeakMap();
    const originalAttributes = new WeakMap();
    const originalTitle = new WeakMap();

    window.hotelI18n = {
        dictionaries: { en: {}, fr: french, sw: swahili },
        getLanguage() {
            try {
                const language = localStorage.getItem('hotel-language');
                return ['en', 'fr', 'sw'].includes(language) ? language : 'en';
            } catch {
                return 'en';
            }
        },
        setLanguage(language) {
            if (!['en', 'fr', 'sw'].includes(language)) return;
            try {
                localStorage.setItem('hotel-language', language);
            } catch {
                // Keep the selected language for the current page if storage is unavailable.
            }
            this.applyLanguage(language);
        },
        applyLanguage(language = this.getLanguage()) {
            const dictionary = this.dictionaries[language] || {};
            document.documentElement.lang = language;

            const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
            let node;
            while ((node = walker.nextNode())) {
                if (!originalText.has(node)) originalText.set(node, node.nodeValue);
                const text = originalText.get(node);
                const trimmed = text.trim();
                if (!trimmed) continue;
                const translated = dynamicText(trimmed, language, dictionary);
                if (translated && translated !== trimmed) {
                    const start = text.indexOf(trimmed);
                    node.nodeValue = `${text.slice(0, start)}${translated}${text.slice(start + trimmed.length)}`;
                } else {
                    node.nodeValue = text;
                }
            }

            document.querySelectorAll('[placeholder], [title], [aria-label], [data-confirm]').forEach((element) => {
                if (!originalAttributes.has(element)) originalAttributes.set(element, {});
                const originals = originalAttributes.get(element);
                for (const attribute of ['placeholder', 'title', 'aria-label', 'data-confirm']) {
                    const value = element.getAttribute(attribute);
                    if (value !== null && !(attribute in originals)) originals[attribute] = value;
                    const original = originals[attribute];
                    if (original !== undefined) element.setAttribute(attribute, dictionary[original] || original);
                }
            });
            document.querySelectorAll('title').forEach((element) => {
                if (!originalTitle.has(element)) originalTitle.set(element, element.textContent);
                const original = originalTitle.get(element);
                element.textContent = dictionary[original] || original;
            });
            document.querySelectorAll('[data-localized-date][datetime]').forEach((element) => {
                const date = new Date(`${element.dateTime}T00:00:00`);
                if (!Number.isNaN(date.getTime())) {
                    const format = element.dataset.dateFormat || 'long';
                    const options = format === 'datetime'
                        ? { day: '2-digit', month: 'long', year: 'numeric', hour: '2-digit', minute: '2-digit' }
                        : format === 'short'
                            ? { day: '2-digit', month: 'long' }
                            : format === 'long'
                                ? { day: '2-digit', month: 'long', year: 'numeric' }
                                : { weekday: 'short', day: '2-digit', month: 'long', year: 'numeric' };
                    element.textContent = new Intl.DateTimeFormat(language, options).format(date);
                }
            });
            document.querySelectorAll('#language-select').forEach((select) => {
                select.value = language;
                select.setAttribute('aria-label', ({
                    en: 'Language',
                    fr: 'Langue',
                    sw: 'Lugha'
                })[language]);
            });
            document.dispatchEvent(new Event('hotel-language-applied'));
        }
    };
